//! The import table Python resolves at run time: every module name
//! `klippy.py` imports (`gcode`, `webhooks`, `configfile`, `pins`, `mcu`,
//! `toolhead`) and every `extras.<name>` / `kinematics.<name>` module file,
//! keyed by its Python import name. A library module without entry points
//! (`extras.shaper_defs`, every `kinematics.*`, which the toolhead imports
//! through its own loader) maps to an empty factory, as importing it in
//! Python succeeds and finds no `load_config`.

use klippy_api::printer::ModuleFactory;
use klippy_core::klippy::{
    ModuleRegistry, MODULE_CONFIGFILE, MODULE_GCODE, MODULE_MCU, MODULE_PINS, MODULE_TOOLHEAD,
    MODULE_WEBHOOKS,
};

fn entry(name: &str, factory: ModuleFactory) -> (String, ModuleFactory) {
    (name.to_string(), factory)
}

fn empty(name: &str) -> (String, ModuleFactory) {
    entry(name, ModuleFactory::default())
}

